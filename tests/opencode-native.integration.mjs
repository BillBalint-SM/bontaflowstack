import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {writeNativeEvidence,writeAcceptanceEvidence} from './fixtures/native-evidence.mjs';

test('native OpenCode discovers the packaged skills and binds its MCP call without rewriting JSONC',{skip:process.env.BFS_RUN_OPENCODE_NATIVE!=='1'},()=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'bfs-opencode-native-')),project=path.join(root,'project with spaces');
  fs.mkdirSync(path.join(project,'.opencode','plugins'),{recursive:true});
  const output=path.join(root,'durable package'),repo=fileURLToPath(new URL('../',import.meta.url));
  const built=spawnSync(process.execPath,[path.join(repo,'scripts/build-host-package.mjs'),'--host','opencode-cli','--output',output],{encoding:'utf8',windowsHide:true});assert.equal(built.status,0,built.stderr);
  fs.writeFileSync(path.join(output,'install-state.json'),JSON.stringify({schema:1,stateHome:path.join(root,'state')}));
  const plugin=pathToFileURL(path.join(output,'plugin.mjs'));
  fs.writeFileSync(path.join(project,'.opencode','plugins','bfs.js'),`export {BontaFlowStack} from ${JSON.stringify(plugin.href)};\n`);
  const original='// Preserve this user comment and trailing comma.\n'+JSON.stringify({$schema:'https://opencode.ai/config.json',share:'disabled',permission:{'*':'ask',bfs_status:'allow'}},null,2).replace(/\n}$/,',\n}')+'\n',configFile=path.join(project,'opencode.jsonc');
  fs.writeFileSync(configFile,original);
  const cli=process.env.BFS_OPENCODE_CLI || path.join(process.env.APPDATA,'npm','node_modules','opencode-ai','bin','opencode.exe');
  const env={...process.env,XDG_CONFIG_HOME:path.join(root,'config')};delete env.BFS_STATE_HOME;delete env.NODE_TEST_CONTEXT;
  const options={cwd:project,env,encoding:'utf8',windowsHide:true,timeout:120000,maxBuffer:8*1024*1024};
  const listed=spawnSync(cli,['debug','skill'],options);assert.equal(listed.status,0,listed.stderr);const skills=JSON.parse(listed.stdout).filter(skill=>skill.name.startsWith('bfs-'));assert.equal(skills.length,34);for(const skill of skills)assert.equal(path.resolve(skill.location),path.join(output,'skills',skill.name,'SKILL.md'));
  const mcp=spawnSync(cli,['mcp','list'],options);assert.equal(mcp.status,0,mcp.stderr);assert.match(mcp.stdout.replace(/\u001b\[[0-9;]*m/g,''),/bfs connected/);
  console.log(`OpenCode package discovered; testing the model call. Evidence: ${root}`);
  const result=spawnSync(cli,['run','--model','opencode/longcat-2.5-preview-free','--format','json','Call bfs_status exactly once with no arguments. Do not use another tool. Report its host and sessionId.'],options);
  const diagnostic=writeNativeEvidence(path.join(root,'native-evidence.json'),result);
  assert.equal(result.status,0,JSON.stringify(diagnostic));
  const events=result.stdout.trim().split('\n').map(JSON.parse),call=events.find(event=>event.type==='tool_use' && event.part?.tool==='bfs_status');
  assert.ok(call,'Missing BFS status call');assert.equal(call.part.state.status,'completed',JSON.stringify(diagnostic));
  const text=call.part.state.output.split('\nBFS_GUARD_OBSERVED')[0];
  const data=JSON.parse(text);
  assert.equal(data.host,'opencode-cli');assert.equal(data.hostWorkspace,project);assert.equal(data.sessionId,call.sessionID);
  assert.match(call.part.state.output,/BFS_GUARD_OBSERVED/);
  const version=spawnSync(cli,['--version'],{encoding:'utf8',windowsHide:true,timeout:15000});assert.equal(version.status,0,version.stderr);
  const file=path.join(root,'result.json');
  assert.equal(fs.readFileSync(configFile,'utf8'),original);
  fs.writeFileSync(file,JSON.stringify({version:version.stdout.trim(),host:data.host,sessionId:data.sessionId,workspace:project,taskId:data.taskId,tool:call.part.tool,guardObserved:true,skillCount:skills.length,skillsRoot:output,configPreserved:true},null,2)+'\n');
  writeAcceptanceEvidence(file);
  console.log(`Native adapter evidence: ${file}`);
});
